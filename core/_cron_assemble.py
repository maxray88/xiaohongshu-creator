#!/usr/bin/env python3
"""
情绪树洞 — 竖版视频笔记合成器 (1080×1920, 9:16)
Edge-TTS 主引擎，全卡统一声音。
自动找到最新的 day 目录，支持 v1/v2。

用法:
  python3 _cron_assemble.py              # 自动找最新 day
  python3 _cron_assemble.py --day 20260723  # 指定日期
"""
import json, os, subprocess, sys, re, time, hashlib

BASE = os.path.expanduser("~/.hermes/data/xhs_treehole")

# ── Edge-TTS 参数（确定性发音，全卡同一声音） ──
TTS_VOICE = "zh-CN-XiaoyiNeural"
TTS_RATE = "+10%"


def find_latest_day():
    """Find the latest day_{date}_day{N}_v2 directory."""
    dirs = sorted([
        d for d in os.listdir(BASE)
        if os.path.isdir(os.path.join(BASE, d)) and d.startswith("day_") and d.endswith("_v2")
    ], reverse=True)
    if not dirs:
        print("[FATAL] No day directories found")
        sys.exit(1)
    return dirs[0]


def resolve_dirs(day_spec):
    """Given a v2 dir name, find v1 counterpart. Fallback to latest V1 if today V1 missing (01:00 offline)."""
    v2_dir = os.path.join(BASE, day_spec)
    v1_name = re.sub(r"_v2$", "", day_spec)
    v1_dir = os.path.join(BASE, v1_name)
    if not os.path.isdir(v1_dir):
        # 01:00 offline → V2 exists (created from previous day's V1) but V1 dir missing
        # Fallback to the most recent V1 that has post_data.json, so video can still be built
        candidates = sorted([d for d in os.listdir(BASE) if os.path.isdir(os.path.join(BASE, d)) and d.startswith("day_") and not d.endswith("_v2")], reverse=True)
        for cand in candidates:
            cand_path = os.path.join(BASE, cand)
            if os.path.isfile(os.path.join(cand_path, "post_data.json")):
                print(f"[WARN] v1 dir not found: {v1_dir} → fallback to latest V1: {cand_path}")
                return cand_path, v2_dir
        print(f"[FATAL] v1 dir not found: {v1_dir} and no fallback V1 available")
        sys.exit(1)
    return v1_dir, v2_dir


def read_manifest(v2_dir):
    """Read manifest.json from v2 dir."""
    m2_path = os.path.join(v2_dir, "manifest.json")
    if not os.path.isfile(m2_path):
        print(f"[FATAL] No manifest.json in {v2_dir}")
        sys.exit(1)
    with open(m2_path, "r", encoding="utf-8") as f:
        return json.load(f)


def read_post_data(v1_dir):
    """Read post_data.json from v1 dir."""
    p1_path = os.path.join(v1_dir, "post_data.json")
    if not os.path.isfile(p1_path):
        return {}
    with open(p1_path, "r", encoding="utf-8") as f:
        return json.load(f)


def clean_tts_text(text, keep_brand=False):
    """Remove dates, emojis, and branding signatures from TTS text."""
    import unicodedata
    text = ''.join(c for c in text if unicodedata.category(c) != 'So')
    text = text.replace('️', '')
    text = re.sub(r'\d{4}[-\\./]\d{1,2}[-\\./]\d{1,2}', '', text)
    if not keep_brand:
        text = re.sub(r'[@#]?\s*情绪树洞\s*[·•]?\s*', '', text)
        text = re.sub(r'[·•]\s*情绪树洞', '', text)
        text = re.sub(r'\s*[·•]\s*', '', text)
        text = re.sub(r'\s*情绪树洞\s*', ' ', text)
    else:
        text = re.sub(r'\s*[·•]\s*', ' · ', text)
    text = re.sub(r'[。，]\s+', lambda m: m.group(0)[0], text)
    text = re.sub(r'\s+', ' ', text).strip()
    text = text.strip('。，,、 ')
    return text


def _truncate_tts(text, limit=300):
    if len(text) <= limit:
        return text
    cut = text[:limit]
    for sep in ["。", "？", "！", "；"]:
        idx = cut.rfind(sep)
        if idx > int(limit * 0.6):
            return cut[:idx + 1]
    return cut.rstrip("，,、 ")


def get_card_texts(v1_dir, manifest, post_data=None):
    """
    Derive TTS text for each card directly from V1/V2 content_text.

    No longer parses HTML — the canonical narrative lives in
    post_data.json:content_text (generated by the 01:00/02:00 LLM crons).
    Each card's TTS is sliced to match its narrative role, so voice
    and visuals stay aligned:

      1 cover   — series + title (hook)
      2 scene   — concrete scene / resonance moment
      3 insight — psychological insight (the "why")
      4 method  — actionable step / reframe
      5 gentle  — gentle closing / self-compassion
      6 cta     — comment invitation around emotion_tag

    post_data may be injected directly (dict) instead of read from
    v1_dir/post_data.json — a test seam mirroring the design's
    llm_caller injection pattern: tests pass fixtures, production
    passes nothing and the file is read.
    """
    if post_data is None:
        post_data = read_post_data(v1_dir)

    series = (post_data.get("series") or manifest.get("series") or "情绪树洞").strip()
    title = (post_data.get("title") or manifest.get("title") or "").strip()
    emotion_tag = (post_data.get("emotion_tag") or manifest.get("emotion_tag") or "").strip()
    body = (post_data.get("content_text") or "").strip()

    if not body:
        print("  [WARN] content_text empty in post_data.json — falling back to title only")
        fallback_body = title or emotion_tag or "今天想和你聊聊心里的话"
        body = fallback_body

    paragraphs = [p.strip() for p in re.split(r'\n\s*\n', body) if p.strip()]
    if not paragraphs:
        paragraphs = [body.strip()]

    texts = {}
    # 段落认领表：每段只许喂给一张卡。两卡念同一段是真实发生过的
    # 故障（day82 卡2/卡3 同为「不是…而是」段、day81 卡4 兜底与
    # 卡5 都落到 paragraphs[-1]），观感上是口播出错、且视频里两屏
    # 字完全一样，比少一段更糟。各卡选段时统一走 _pick。
    claimed = set()

    def _pick(match, *, reverse=False, exclude_last=False):
        """从未被认领的段落里选第一个满足 match(text) 的段并认领。

        match 为 None 表示只要还有剩余段落就取（按 reverse 方向）。
        没有可用段时返回 None —— 调用方负责兜底，但绝不允许退回到
        已被别的卡认领的段（那正是本 bug 的成因）。
        """
        pool = [i for i in range(len(paragraphs))
                if i not in claimed and not (exclude_last and i == len(paragraphs) - 1)]
        order = pool[::-1] if reverse else pool
        for i in order:
            if match is None or match(paragraphs[i]):
                claimed.add(i)
                return paragraphs[i]
        return None

    def _any(*kws):
        return lambda t: any(k in t for k in kws)

    # ── Card 1: cover — series + title ──
    cover_raw = f"这里是{series}，今天想和你聊聊，{title}。"
    texts[1] = _truncate_tts(clean_tts_text(cover_raw, keep_brand=True), 300)

    # ── Card 2: scene — 2nd paragraph (the lived scene) ──
    # 固定第 2 段（内容少时用第 1 段），先认领，
    # 卡3/卡4 的关键词扫描就自动绕开它。
    scene_idx = 1 if len(paragraphs) >= 2 else 0
    claimed.add(scene_idx)
    texts[2] = _truncate_tts(clean_tts_text(paragraphs[scene_idx]), 300)

    # ── Card 3: insight — definition / psychological insight ──
    # 「不是…而是」是本系列招牌句式，卡2 的场景段常含同一句式
    # （day82 上司那段同时命中两卡），必须靠 claimed 排除。
    insight_raw = (_pick(lambda t: "心理学" in t or t.startswith("这就是"))
                   or _pick(lambda t: "不是" in t and "而是" in t)
                   or _pick(None))
    texts[3] = _truncate_tts(clean_tts_text(insight_raw or paragraphs[0]), 300)

    # ── Card 4: method — actionable reframe / coping step ──
    # exclude_last：收尾段属于卡5，别被关键词（"今晚"）误当成方法。
    method_raw = (_pick(_any("试着", "试试", "可以试", "下次", "今晚", "当你",
                             "记得", "别忘了", "从今天起"),
                        reverse=True, exclude_last=True)
                  or _pick(None, reverse=True, exclude_last=True)
                  or paragraphs[0])
    # CTA invitation lines occasionally leak into method paragraphs — strip them
    method_raw = "。".join(s for s in method_raw.split("。") if "评论区" not in s and "评论" not in s)
    texts[4] = _truncate_tts(clean_tts_text(method_raw), 300)

    # ── Card 5: gentle — final compassionate closing (last paragraph) ──
    # 卡5 优先收尾段；收尾段若已被认领（段落极少时），退回任意未认领段，
    # 宁可念别的段也不与前面撞车。
    last = len(paragraphs) - 1
    gentle_raw = (paragraphs[last] if last not in claimed
                  else (_pick(None, reverse=True) or paragraphs[last]))
    claimed.add(last)
    gentle_raw = "。".join(s for s in gentle_raw.split("。") if "评论区" not in s and "评论" not in s)
    if not gentle_raw.strip():
        gentle_raw = paragraphs[last]
    texts[5] = _truncate_tts(clean_tts_text(gentle_raw), 300)

    # ── Card 6: cta — comment invitation (generated, not sliced) ──
    if emotion_tag:
        cta_raw = f"你最近一次感到{emotion_tag}，是在什么时候呢？欢迎在评论区说说你的故事，情绪树洞替你收着。"
    else:
        cta_raw = "你有什么想说的心里话吗？欢迎在评论区说说你的故事，情绪树洞替你收着。"
    texts[6] = _truncate_tts(clean_tts_text(cta_raw, keep_brand=True), 300)

    # Safety: ensure every index 1..6 exists and is non-empty
    for i in range(1, 7):
        if not texts.get(i) or not texts[i].strip():
            texts[i] = _truncate_tts(clean_tts_text(paragraphs[0] if paragraphs else body), 300)

    return texts, title, series, emotion_tag


def get_audio_duration(mp3_path):
    """Get duration of MP3 in seconds using ffprobe."""
    r = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", mp3_path],
        capture_output=True, text=True
    )
    try:
        return float(r.stdout.strip())
    except ValueError:
        return 0.0


def _valid_mp4(path, expected_duration):
    """True if `path` is a readable MP4 whose duration roughly matches expected."""
    if not os.path.isfile(path) or os.path.getsize(path) < 1024:
        return False
    r = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", path],
        capture_output=True, text=True
    )
    try:
        actual = float(r.stdout.strip())
    except ValueError:
        return False
    return actual > 0.5 and abs(actual - expected_duration) <= 3.0


def generate_tts(texts, video_dir):
    """
    Generate TTS for all cards using Edge-TTS (统一声音).
    Skips cards that already have valid cached MP3s.
    Returns (durations_dict, engine_name).
    """
    durations = {}
    edge_ok = subprocess.run(["which", "edge-tts"], capture_output=True).returncode == 0
    if not edge_ok:
        print("[FATAL] edge-tts not found. Install with: pip install edge-tts")
        sys.exit(1)

    print(f"\n[STEP 3] Generating TTS audio (Edge-TTS, {TTS_VOICE}, {TTS_RATE})...")

    for i in sorted(texts.keys()):
        text = texts.get(i, "").strip()
        last_error = ""   # 首次就失败时也要能报出原因
        if not text:
            durations[i] = 0.0
            continue

        mp3_path = os.path.join(video_dir, f"card_{i}.mp3")

        # Cache check — reuse if valid.
        #
        # 关键：缓存有效性必须绑定**文本内容**，不只是「文件存在且 >1000 字节」。
        # 旧实现只看文件大小，于是改了文案（01:30 去AI味、或 04:00 重跑
        # 修好切片 bug）之后，卡2/卡3 仍复用旧音频 —— 视频里的声音
        # 和卡片文字对不上，而且没有任何提示。2026-09-27 day82 就是这样：
        # 修好「两卡念同一段」后重跑 04:00，必须手动删 mp3 才能生效。
        text_hash = hashlib.sha1(text.encode("utf-8")).hexdigest()[:12]
        hash_path = os.path.join(video_dir, f"card_{i}.txt")
        cached_ok = (
            os.path.isfile(mp3_path) and os.path.getsize(mp3_path) > 1000
            and os.path.isfile(hash_path)
            and open(hash_path, encoding="utf-8").read().strip() == text_hash
        )
        if cached_ok:
            dur = get_audio_duration(mp3_path)
            if dur > 0.5:
                print(f"  [CACHE] card_{i}.mp3 ({dur:.2f}s)")
                durations[i] = dur
                continue
        elif os.path.isfile(mp3_path) and os.path.getsize(mp3_path) > 1000:
            print(f"  ♻️  card_{i}.mp3 缓存已过期（文案变了）—— 重新生成")

        t1 = time.time()
        # Retry transient failures (DNS, network glitches)
        last_error = ""
        for attempt in range(3):
            r = subprocess.run(
                ["edge-tts", "--voice", TTS_VOICE, "--rate", TTS_RATE,
                 "--text", text, "--write-media", mp3_path],
                capture_output=True, text=True, timeout=120,
            )
            if r.returncode == 0 and os.path.isfile(mp3_path) and os.path.getsize(mp3_path) > 1000:
                break
            # 记下最后一次失败原因：旧代码赋值却从不使用，
            # 于是重试 3 次全失败后只报一句「failed (exit N)」，
            # 看不到 stderr 里的真实原因（DNS? 配额? 声音名不对?）。
            last_error = r.stderr.strip()[-300:]
            if attempt < 2:
                print(f"  ⚠️  retry {attempt + 1}/3 for card_{i}...")
                time.sleep(5)
        wall = time.time() - t1

        if r.returncode == 0 and os.path.isfile(mp3_path) and os.path.getsize(mp3_path) > 1000:
            dur = get_audio_duration(mp3_path)
            durations[i] = round(dur, 1)
            # 记录文本指纹，供下次运行判断缓存是否过期
            try:
                with open(hash_path, "w", encoding="utf-8") as f:
                    f.write(text_hash)
            except OSError as e:
                print(f"     (无法写指纹文件，下次将重新生成: {e})")
            print(f"  ✅ card_{i}.mp3 ({dur:.1f}s, {wall:.1f}s wall)")
        else:
            print(f"  ⚠️  card_{i}.mp3 failed (exit {r.returncode})")
            if r.stderr:
                print(f"     stderr: {r.stderr.strip()[-300:]}")
            if last_error and last_error != r.stderr.strip()[-300:]:
                print(f"     last retry error: {last_error}")
            durations[i] = 0.0

    # Validate: need at least 6 cards with valid TTS duration
    valid = {k: v for k, v in durations.items() if v > 0.5}
    if len(valid) < 6:
        failed_cards = [k for k in sorted(durations.keys()) if durations.get(k, 0) <= 0.5]
        print(f"[FATAL] Only {len(valid)}/6 valid TTS files. Failed cards: {failed_cards}")
        sys.exit(1)

    return durations, "edge-tts"


def build_segments(manifest, images_dir, video_dir, durations):
    """Build and concatenate video segments."""
    print("\n[STEP 4] Building video segments...")
    segments = []
    card_types = {}
    for card in manifest.get("cards", []):
        i = card["index"]
        img_file = card["file"]
        img_path = os.path.join(images_dir, img_file)
        if not os.path.isfile(img_path):
            print(f"  [ERROR] Image not found: {img_path}")
            continue
        dur = durations.get(i, 3.0)
        padded_path = os.path.join(video_dir, f"pad_{i}.png")
        seg_path = os.path.join(video_dir, f"seg_{i}.mp4")
        mp3_path = os.path.join(video_dir, f"card_{i}.mp3")

        r = subprocess.run([
            "ffprobe", "-v", "error", "-select_streams", "v:0",
            "-show_entries", "stream=width,height", "-of", "csv=p=0", img_path
        ], capture_output=True, text=True)
        if r.returncode != 0:
            # manifest 指向了非图片（如 .html 残留，day70 事故）：ffprobe 直接失败。
            # 在此大声拦截，而不是让下游 pad/seg 报 6 条难懂的错。
            print(f"  [ERROR] Not a readable image: {img_path} "
                  f"(manifest file 字段疑似未翻转 .html→.jpg)")
            continue
        dims = r.stdout.strip().split(",")
        ow, oh = (int(dims[0]), int(dims[1])) if len(dims) == 2 else (1080, 1440)
        ctype = card.get("type", f"card{i}")
        card_types[i] = ctype
        print(f"  card_{i} ({ctype}): {ow}×{oh}, TTS {dur:.2f}s")

        # Pad to 1080×1920
        r = subprocess.run([
            "ffmpeg", "-y", "-i", img_path,
            "-vf", "scale='min(1080,iw)':'min(1920,ih)':force_original_aspect_ratio=decrease,pad=1080:1920:(ow-iw)/2:(oh-ih)/2:color=#1A1A2E",
            "-frames:v", "1", padded_path
        ], capture_output=True, text=True, timeout=30)
        if r.returncode != 0 or not os.path.isfile(padded_path):
            print(f"  [ERROR] pad {i} failed: {r.stderr[-200:]}")
            continue

        # Video segment — try Hyperframes (Ken Burns + safe margin) first, then ffmpeg
        # Hyperframes adds gentle motion to static cards; ffmpeg is the proven still-image fallback.
        hf_ok = False
        try:
            from hyperframes_pipeline import render_segment as hf_render
            hf_ok = hf_render(padded_path, dur, seg_path)
            if hf_ok:
                print(f"  [OK] seg_{i}.mp4 ({dur:.2f}s) via Hyperframes")
                segments.append(seg_path)
                continue
        except Exception:
            hf_ok = False

        r = subprocess.run([
            "ffmpeg", "-y", "-loop", "1", "-i", padded_path, "-i", mp3_path,
            "-c:v", "libx264", "-preset", "veryfast", "-t", f"{dur:.3f}", "-pix_fmt", "yuv420p",
            "-c:a", "aac", "-b:a", "128k", "-shortest", seg_path
        ], capture_output=True, text=True, timeout=120)

        if r.returncode != 0:
            print(f"  [ERROR] seg {i} failed: {r.stderr[-200:]}")
            continue
        segments.append(seg_path)
        print(f"  [OK] seg_{i}.mp4 ({dur:.2f}s)")

    if len(segments) < 6:
        print(f"[FATAL] Only {len(segments)} segments, need 6")
        sys.exit(1)
    return segments, card_types


def concat_segments(segments, video_dir, expected_duration):
    """Concat demuxer.

    All segments are encoded identically by build_segments, so a stream-copy
    concat is near-instant and lossless; fall back to a fast re-encode if the
    copy output is invalid (the proven uploadable format).
    """
    print("\n[STEP 5] Concatenating segments...")
    list_file = os.path.join(video_dir, "video_list.txt")
    with open(list_file, "w") as f:
        for seg in segments:
            f.write(f"file '{seg}'\n")
    output_path = os.path.join(video_dir, "video_note.mp4")

    r = subprocess.run([
        "ffmpeg", "-y", "-f", "concat", "-safe", "0", "-i", list_file,
        "-c", "copy", "-movflags", "+faststart", output_path
    ], capture_output=True, text=True, timeout=120)
    if r.returncode == 0 and _valid_mp4(output_path, expected_duration):
        print("  [OK] concatenated via stream copy (lossless, fast)")
    else:
        print("  stream copy produced invalid output — re-encoding (veryfast)")
        r = subprocess.run([
            "ffmpeg", "-y", "-f", "concat", "-safe", "0", "-i", list_file,
            "-c:v", "libx264", "-preset", "veryfast", "-crf", "23",
            "-c:a", "aac", "-b:a", "128k", "-movflags", "+faststart", output_path
        ], capture_output=True, text=True, timeout=300)
        # 重编码后必须同样校验：returncode==0 不代表产物可用
        # （day70 事故的教训：ffmpeg 静默产出损坏文件，一路带到发布才炸）。
        if r.returncode == 0 and not _valid_mp4(output_path, expected_duration):
            got = get_audio_duration(output_path)
            print(f"  [ERROR] re-encode exited 0 but output is invalid "
                  f"(expected ≈{expected_duration:.1f}s, got {got:.1f}s)")
            sys.exit(1)
    if r.returncode != 0:
        print(f"[ERROR] Concat failed: {r.stderr[-500:]}")
        sys.exit(1)

    r = subprocess.run([
        "ffprobe", "-v", "error", "-show_entries", "format=duration,size",
        "-of", "csv=p=0", output_path
    ], capture_output=True, text=True)
    finfo = r.stdout.strip().split(",")
    # ffprobe 对某些容器返回 "N/A" —— 直接 float() 会崩，
    # 而这里崩掉等于丢掉已经生成好的视频
    try:
        final_duration = float(finfo[0]) if len(finfo) > 0 else 0.0
    except (ValueError, IndexError):
        final_duration = 0.0
    try:
        final_size = int(float(finfo[1])) if len(finfo) > 1 else 0
    except (ValueError, IndexError):
        final_size = 0
    r = subprocess.run([
        "ffprobe", "-v", "error", "-select_streams", "v:0",
        "-show_entries", "stream=width,height", "-of", "csv=p=0", output_path
    ], capture_output=True, text=True)
    vdims = r.stdout.strip().split(",")
    vw, vh = vdims if len(vdims) == 2 else ("1080", "1920")
    return output_path, final_duration, final_size, vw, vh


def cleanup(video_dir):
    """Remove temp files."""
    print("\n[STEP 6] Cleaning up...")
    cleaned = 0
    for i in range(1, 7):
        for fname in [f"pad_{i}.png", f"seg_{i}.mp4"]:
            fp = os.path.join(video_dir, fname)
            if os.path.isfile(fp):
                os.remove(fp)
                cleaned += 1
    for fname in ["video_list.txt", "_tts_config.json"]:
        fp = os.path.join(video_dir, fname)
        if os.path.isfile(fp):
            os.remove(fp)
            cleaned += 1
    print(f"  Removed {cleaned} temp files. Keeping: video_note.mp4 + card_*.mp3 + card_*.txt")


def main():
    if len(sys.argv) > 2 and sys.argv[1] == "--day":
        day_date = sys.argv[2]
        candidates = sorted([
            d for d in os.listdir(BASE)
            if os.path.isdir(os.path.join(BASE, d))
            and d.startswith(f"day_{day_date}") and d.endswith("_v2")
        ], reverse=True)
        if not candidates:
            print(f"[FATAL] Day {day_date} v2 not found")
            sys.exit(1)
        v2_name = candidates[0]
    else:
        v2_name = find_latest_day()
        # 自动路径只合成「今天」的素材。01:00/02:00 生成历史上有 ~13% 的天数失败，
        # 这时最新 _v2 会落到昨天——重编码昨天视频纯属浪费（05:00 发布/03:00 填表/
        # 02:30 渲染已有同样守卫），且产物无人消费；直接跳过，06:00 watchdog 仍会
        # 以「今天没有生成新内容」告警。显式 --day 的历史目录不受影响（手动重合成保留）。
        v2_date = re.search(r"day_(\d{8})", v2_name)
        if not v2_date or v2_date.group(1) != time.strftime("%Y%m%d"):
            print(f"  ⏭ 最新素材是 {v2_name}（日期 {v2_date.group(1) if v2_date else '?'}），"
                  f"不是今天——跳过合成，避免对昨天视频做无谓重编码")
            sys.exit(0)

    v1_dir, v2_dir = resolve_dirs(v2_name)
    date_match = re.search(r"day_(\d{8})", v2_name)
    day_date = date_match.group(1) if date_match else "?"
    day_num_match = re.search(r"day(\d+)$", re.sub(r"_v2$", "", v2_name))
    day_num = day_num_match.group(1) if day_num_match else "?"

    print(f"[INFO] v2: {v2_name}")
    print(f"[INFO] v1: {os.path.basename(v1_dir)}")

    manifest = read_manifest(v2_dir)
    images_dir = os.path.join(v2_dir, "images")
    video_dir = os.path.join(v2_dir, "video")
    os.makedirs(video_dir, exist_ok=True)

    # Step 1: Verify images
    print(f"\n[STEP 1] Verifying images in {images_dir}...")
    missing = []
    for card in manifest.get("cards", []):
        p = os.path.join(images_dir, card["file"])
        ok = os.path.isfile(p)
        print(f"  {card.get('file','?')}: {'✓' if ok else '✗'}")
        if not ok:
            missing.append(card.get('file','?'))
    # Self-heal: if 02:30 render was skipped (V2 born after 02:30), JPGs will be missing
    # but HTML exists — render inline so 04:00 never fails on pad_*.png
    if missing:
        # 原先这里还有一个 has_html 变量，算了却从不用（pyflakes 长期报警）——
        # 它试图用「缺失文件名换成 .html 是否存在」来推断，但那种推断在
        # 目录里同时残留 HTML 和 JPG 时会给出误导性结论。下面的
        # html_count 是更直接的判据。
        html_count = len([f for f in os.listdir(images_dir) if f.endswith('.html')]) if os.path.isdir(images_dir) else 0
        if html_count >= 6:
            print(f"  ⚠️  {len(missing)} JPG missing but {html_count} HTML present — triggering inline render (02:30 was skipped)")
            try:
                proj = os.path.expanduser("~/02_Cronjobs_Projects/01_XHS_Daily_Post")
                r = subprocess.run(["bash", os.path.join(proj, "bin/render_xhs_cards.sh")], capture_output=True, text=True, timeout=180)
                print(r.stdout[-800:] if r.stdout else "")
                if r.stderr:
                    print(r.stderr[-400:])
                # reload manifest after render (flips .html→.jpg, images_rendered:true)
                manifest = read_manifest(v2_dir)
                # re-verify
                for card in manifest.get("cards", []):
                    p = os.path.join(images_dir, card["file"])
                    if not os.path.isfile(p):
                        print(f"  [FATAL] Still missing after inline render: {p}")
                        sys.exit(1)
                print("  ✅ Inline render succeeded")
            except Exception as e:
                print(f"  [FATAL] Inline render failed: {e}")
                sys.exit(1)
        else:
            print(f"  [FATAL] {len(missing)} images missing and no HTML to render from")
            sys.exit(1)

    # Step 2: Derive TTS texts from content_text (post_data.json) — one slice per card role
    print(f"\n[STEP 2] Deriving TTS texts from content_text (post_data.json)...")
    texts, title, series, emotion_tag = get_card_texts(v1_dir, manifest)
    for i, t in sorted(texts.items()):
        preview = t[:60] + ("…" if len(t) > 60 else "")
        print(f"  Card {i}: {len(t)} chars — {preview}")

    # Step 3: TTS — S2-Pro primary, Edge-TTS fallback
    durations, engine_used = generate_tts(texts, video_dir)
    print(f"  Durations: { {k: f'{v:.2f}s' for k, v in durations.items()} }")

    # Step 4-5: Build + concat
    segments, card_types = build_segments(manifest, images_dir, video_dir, durations)
    expected_duration = sum(durations.values())
    output_path, fdur, fsize, vw, vh = concat_segments(segments, video_dir, expected_duration)

    # Step 6: Cleanup
    cleanup(video_dir)

    # ── Report ──
    print("\n" + "=" * 64)
    print("📹 情绪树洞 · 竖版视频笔记合成报告")
    print("=" * 64)
    print(f"  日期:         {day_date} (Day {day_num})")
    print(f"  系列:         {series}")
    print(f"  标题:         {title}")
    print(f"  情绪标签:     {emotion_tag}")
    print(f"  版本:         v2")
    print(f"  画布:         {vw}×{vh} (9:16 竖版)")
    print(f"  TTS 引擎:     {engine_used}")
    print(f"  配音一致性:   ✅ 同一声音（同一引擎同一参数）")
    print("-" * 64)
    print(f"  视频时长:     {fdur:.2f}s ({fdur/60:.1f} 分钟)")
    print(f"  文件大小:     {fsize/1024/1024:.1f} MB")
    print(f"  输出路径:     {output_path}")
    print("-" * 64)
    print("  TTS 时长分布:")
    total = sum(durations.values())
    for card in manifest.get("cards", []):
        i = card["index"]
        dur = durations.get(i, 0)
        pct = dur / total * 100 if total > 0 else 0
        bar = "█" * int(pct / 5) + "░" * (20 - int(pct / 5))
        ctype = card_types.get(i, f"card{i}")
        print(f"    Card {i} ({ctype:8s}): {dur:6.2f}s  {bar}  {pct:3.0f}%")
    print(f"    {'─' * 48}")
    print(f"    总 TTS: {total:.2f}s")
    print("=" * 64)


if __name__ == "__main__":
    main()
